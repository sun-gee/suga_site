/// Draws the mark for a step, all about the same size: A (Don) = filled circle, B (Pang) = filled triangle,
/// C (Tsu) = thin outlined circle, off = a small dot.
class _StepMarkPainter extends CustomPainter {
  _StepMarkPainter(this.step, this.color);

  final int step;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final center = size.center(Offset.zero);
    final r = size.shortestSide / 2;
    final markRadius = r * 0.63;
    final stroke = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = r * 0.23
      ..strokeJoin = StrokeJoin.round;
    final fill = Paint()..color = color;
    switch (step) {
      case _off:
        canvas.drawCircle(center, r * 0.23, fill);
      case _stepA:
        canvas.drawCircle(center, markRadius + stroke.strokeWidth / 2, fill);
      case _stepB:
        // Equilateral triangle pointing up, centered on its centroid. Slightly larger than the circles,
        // since a triangle looks smaller than a circle of the same width.
        final h = markRadius * 2.1;
        final path = Path()
          ..moveTo(center.dx, center.dy - h * 2 / 3)
          ..lineTo(center.dx + h / math.sqrt(3), center.dy + h / 3)
          ..lineTo(center.dx - h / math.sqrt(3), center.dy + h / 3)
          ..close();
        canvas.drawPath(path, fill);
        canvas.drawPath(path, stroke); // Rounds the corners
      case _stepC:
        canvas.drawCircle(center, markRadius, stroke);
    }
  }

  @override
  bool shouldRepaint(_StepMarkPainter old) => old.step != step || old.color != color;
}

/// The mark for [step] at [size], in [color].
Widget _stepMark(int step, double size, Color color) =>
    CustomPaint(size: Size.square(size), painter: _StepMarkPainter(step, color));

/// A multi-part beat grid: one row of steps per part, each step off, A, B or C.
/// Each part has its own A, B and C sounds and a volume.
class _Pattern {
  _Pattern({
    required this.measures,
    required this.beatsPerMeasure,
    required this.beats,
    required this.sounds,
    List<String>? soundsB,
    List<String>? soundsC,
    required this.volumes,
  }) : soundsB = soundsB ?? List.of(sounds),
       soundsC = soundsC ?? List.of(sounds);

  int measures;
  int beatsPerMeasure;
  List<List<int>> beats;
  List<String> sounds; // Sound A per part
  List<String> soundsB;
  List<String> soundsC;
  List<double> volumes;

  int get parts => beats.length;
  int get totalBeats => measures * beatsPerMeasure;

  /// The per-part sound list that [step] (A, B or C) plays.
  List<String> soundsFor(int step) => [sounds, soundsB, soundsC][step - 1];
}

/// The Suga hand-to-hand split patterns. Each has three parts (AB, AC, BB), one line per part:
/// `.` = off, `A`/`B`/`C` = Don/Pang/Tsu, `|` = bar line. Every bar must be the same length.
/// Each step is a 16th note.
const _sugaPatterns = {
  'Down': [
    'A . A . | B . C . | C . A . | B . C .',
    'A . A . | B . C . | C . A . | C . B .',
    'C . A . | B . C . | C . A . | B . C .',
  ],
  'Up': [
    '. C . C | . C . B | . B . A | . C . C',
    '. C . C | . C . B | . B . C | . C . C',
    '. B . A | . C . C | . B . A | . C . C',
  ],
};
// The three parts are named AB, AC and BB.
const _partNames = ['AB', 'AC', 'BB'];
// "Full" plays the parts one after another in this order: AB, AB, AC, BB.
const _fullPartOrder = [0, 0, 1, 2];

/// The steps of one pattern line, e.g. `'A . A . | B . C .'`.
List<int> _parseSteps(String line) => [
  for (final c in line.replaceAll(RegExp(r'[\s|]'), '').split(''))
    switch (c) {
      'A' => _stepA,
      'B' => _stepB,
      'C' => _stepC,
      _ => _off,
    },
];

/// [_sugaPatterns] parsed: direction -> part -> steps.
final _sugaSteps = {
  for (final e in _sugaPatterns.entries) e.key: [for (final line in e.value) _parseSteps(line)],
};

/// [lines] as a pattern that plays [sounds] (sound A, B, C) in every part.
_Pattern _sugaPattern(List<String> lines, List<String> sounds) {
  final bars = lines.first.split('|');
  return _Pattern(
    measures: bars.length,
    beatsPerMeasure: bars.first.replaceAll(' ', '').length,
    beats: [for (final line in lines) _parseSteps(line)],
    sounds: List.filled(lines.length, sounds[0]),
    soundsB: List.filled(lines.length, sounds[1]),
    soundsC: List.filled(lines.length, sounds[2]),
    volumes: List.filled(lines.length, 1.0),
  );
}

