class _MetronomePageState extends State<MetronomePage> {
  // One pool per sound name, so the same sample can overlap itself and parts can share it.
  final AudioEngine _engine = AudioEngine();
  final AudioRecorder _audioRecorder = AudioRecorder();

  int _bpm = 60;
  bool _isPlaying = false;
  // Sequencer position. Steps are generated slightly ahead of playback (see AudioEngine), so these run ahead of
  // what is heard; the display follows the audio through [_cues] instead.
  int _currentBeat = 0;
  int _currentSubdivision = 0;

  // Display, kept in step with the audio: each cue is applied once playback reaches its frame.
  Timer? _displayTimer;
  final List<(int, VoidCallback)> _cues = [];
  final ValueNotifier<int> _flashingBeat = ValueNotifier<int>(-1); // Beat currently flashing (-1 = none)
  int _flashUntilFrame = 0;
  int _lastBeat = 0; // Most recent beat heard, kept between flashes for the display and the tap pad
  int _lastBeatFrame = 0; // Output frame where [_lastBeat] started

  // The pattern being played: the plain metronome, or the selected Suga pattern.
  late _Pattern _pattern = _sectionPattern();

  int _tab = 0; // 0 = Practice, 1 = Sounds
  String _tapSound = _defaultTapSound; // Sound the tap pad plays outside a Suga pattern
  bool _tapPressed = false;

  // Plain metronome
  int _time = 4; // Beats per bar
  int _subdivision = 2; // 1=normal, 2=eighths, 3=triplets, 4=sixteenths (not with a Suga pattern)
  String _clickSound = _defaultClickSound;

  // Suga patterns
  bool _useSuga = false;
  String _sugaChoice = 'Down Full'; // Direction and what to play, e.g. "Down Full" or "Up AC"
  final List<String> _sugaSounds = List.of(_defaultSugaSounds); // Don, Pang, Tsu (pattern A, B, C)
  bool _sugaClick = false; // Also play the metronome click on each beat of a Suga pattern
  static const _countInBeats = 4;

  // Speed up: raise the BPM after every few bars (or pattern loops)
  bool _speedEnabled = false;
  int _speedStartBpm = 60; // Tempo Start jumps to while Speed Up is on
  int _speedMeasures = 2; // Bars (or groove loops) before each BPM increase
  int _speedBpmIncrement = 2;
  int _speedEndingBpm = 120; // Stops speeding up here, but keeps playing
  int _speedMeasuresPlayed = 0;

  // Count-in before the groove starts
  int _countInLeft = 0; // Steps of count-in still to generate
  int _countInBeat = 0; // Count-in beat being heard (1-4), or 0 when not counting in

  // Tap tempo
  final List<int> _tapTimestamps = [];
  Timer? _tapResetTimer;

  // Create Sound
  Uint8List? _recordedAudio; // The (trimmed) audio to preview and save
  String _loadedAudioName = ''; // Name of the original recording or upload
  String _trimNote = '';
  bool _trimmed = false;
  bool _isRecording = false;
  final Set<String> _customSounds = {};
  final TextEditingController _soundNameController = TextEditingController();

  List<String> get _allSounds => [..._builtInSounds, ..._customSounds];

  @override
  void initState() {
    super.initState();
    _loadBuiltInSounds();
    // Groove sounds can point at custom sounds, so restore them once those are loaded.
    _loadCustomSounds().then((_) => _loadGrooveSounds());
  }

  @override
  void dispose() {
    _engine.stop();
    _displayTimer?.cancel();
    _tapResetTimer?.cancel();
    _flashingBeat.dispose();
    _audioRecorder.dispose();
    _soundNameController.dispose();
    super.dispose();
  }

  // ---------------------------------------------------------------------------
  // Audio

  Future<void> _loadBuiltInSounds() async {
    for (final name in _builtInSounds) {
      try {
        final data = await rootBundle.load('assets/sounds/$name.wav');
        await _engine.load(name, data.buffer.asUint8List(data.offsetInBytes, data.lengthInBytes));
      } catch (e) {
        debugPrint('Could not load sound "$name": $e');
      }
    }
  }

  /// Plays [name] immediately, for taps and previews. Metronome sounds go through [_engine.schedule] instead.
  void _playSound(String name, [double volume = 1.0]) => _engine.playNow(name, volume: volume);

  /// Schedules everything due on [beat] to start exactly at output [frame].
  void _playBeat(int beat, int frame) =>
      _soundsDue(beat).forEach((sound, volume) => _engine.schedule(sound, volume, frame));

  /// Everything due on [beat], as sound name -> volume. Sounds are collected first so a sound that is due twice
  /// at once (say the metronome click and a pattern step both using "tick") plays once instead of stacking on
  /// itself.
  Map<String, double> _soundsDue(int beat) {
    final due = <String, double>{}; // Sound name -> loudest volume asked for
    void add(String sound, double volume) => due[sound] = math.max(due[sound] ?? 0, volume);
    void addStep(int part, int step) {
      final s = _pattern.beats[part][step];
      if (s != _off) add(_pattern.soundsFor(s)[part], _pattern.volumes[part]);
    }

    if (_useSuga) {
      // Suga patterns play their parts one after another (see _partOrder), one pass each.
      final step = beat % _pattern.totalBeats;
      addStep(_partAt(beat), step);
      // Each pattern "bar" is one beat: click on its first step, with the downbeat sound at the start of a pass.
      if (_sugaClick && step % _pattern.beatsPerMeasure == 0) {
        add(_clickSound, step == 0 ? 1.0 : _beatVolume);
      }
    } else {
      for (var part = 0; part < _pattern.parts; part++) {
        addStep(part, beat);
      }
    }
    return due;
  }

  /// "Down" or "Up".
  String get _sugaDirection => _sugaChoice.split(' ').first;

  /// The parts played in sequence: just the chosen one, or for Full, [_fullPartOrder].
  List<int> get _partOrder {
    final play = _sugaChoice.split(' ').last;
    return play == 'Full' ? _fullPartOrder : [_partNames.indexOf(play)];
  }

  /// The part playing at global beat [beat] of a Suga pattern.
  int _partAt(int beat) => _partOrder[(beat ~/ _pattern.totalBeats) % _partOrder.length];

  void _setSugaChoice(String choice) => _reconfigure(() {
    _sugaChoice = choice;
    _pattern = _sectionPattern();
  });

  /// Sets the Don, Pang or Tsu sound ([step]) for every part of the Suga pattern.
  void _setSugaSound(int step, String sound) {
    setState(() {
      _sugaSounds[step - 1] = sound;
      if (_useSuga) _pattern.soundsFor(step).fillRange(0, _pattern.parts, sound);
    });
    _saveGrooveSounds();
  }

  void _playSubdivisionClick(int frame) => _engine.schedule(_clickSound, _subdivisionVolume, frame);

  // ---------------------------------------------------------------------------
  // Timing

  /// Beats in one loop: "Time" beats per bar, or for a Suga pattern every part in [_partOrder].
  int get _loopLength => _useSuga ? _pattern.totalBeats * _partOrder.length : _pattern.measures;

  /// Suga pattern steps are 16th notes.
  double get _beatIntervalMs => 60000 / _bpm / (_useSuga ? 4 : 1);

  int get _activeSubdivision => _useSuga ? 1 : _subdivision;

  double get _clickIntervalMs => _beatIntervalMs / _activeSubdivision;

  double get _framesPerBeat => _beatIntervalMs * AudioEngine.rate / 1000;

  void _startMetronome() {
    if (_isPlaying) return;
    _currentBeat = 0;
    _currentSubdivision = 0;
    _speedMeasuresPlayed = 0;
    if (_speedEnabled) _bpm = _speedStartBpm;
    // The groove always starts after a one-bar count-in, counted in its own steps.
    _countInLeft = _useSuga ? _countInBeats * _pattern.beatsPerMeasure : 0;
    _cues.clear();
    _lastBeat = 0;
    _lastBeatFrame = 0;
    _flashUntilFrame = 0;

    _engine.start(_onStep);
    keepScreenAwake(true);
    _displayTimer = Timer.periodic(const Duration(milliseconds: 8), (_) => _syncDisplay());
    setState(() {
      _isPlaying = true;
      _countInBeat = _countInLeft > 0 ? 1 : 0;
    });
  }

  /// The engine asks for each step, slightly ahead of time, with the step's exact output [frame].
  /// Returns the milliseconds until the next step, so tempo changes apply from the next step on.
  double _onStep(int frame) {
    _click(frame);
    return _clickIntervalMs;
  }

  /// Queues [change] to happen on screen when playback reaches [frame].
  void _cue(int frame, VoidCallback change) => _cues.add((frame, change));

  /// Applies every cue the audio has reached, and ends the beat flash on time.
  void _syncDisplay() {
    if (!_isPlaying || !mounted) return;
    final played = _engine.playedFrames;
    var changed = false;
    while (_cues.isNotEmpty && _cues.first.$1 <= played) {
      _cues.removeAt(0).$2();
      changed = true;
    }
    if (_flashingBeat.value >= 0 && played >= _flashUntilFrame) {
      _flashingBeat.value = -1;
      changed = true;
    }
    if (changed) setState(() {});
  }

  void _click(int frame) {
    if (_countInLeft > 0) {
      _countInClick(frame);
      return;
    }
    if (_currentSubdivision == 0) {
      _playBeat(_currentBeat, frame);
      final beat = _currentBeat;
      // Flash for ~1/4 beat (50-100 ms).
      final flashFrames = ((60000 / _bpm / 4).clamp(50, 100) * AudioEngine.rate / 1000).round();
      _cue(frame, () {
        _countInBeat = 0;
        _lastBeat = beat;
        _lastBeatFrame = frame;
        _flashingBeat.value = beat;
        _flashUntilFrame = frame + flashFrames;
      });
    } else {
      _playSubdivisionClick(frame);
    }

    _currentSubdivision = (_currentSubdivision + 1) % _activeSubdivision;
    if (_currentSubdivision != 0) return;

    _currentBeat = (_currentBeat + 1) % _loopLength;
    if (_speedEnabled && _currentBeat == 0) _onSpeedLoopComplete();
  }

  /// One step of the count-in: a click on each beat (the first accented), whether or not the Metronome is on.
  void _countInClick(int frame) {
    final step = _countInBeats * _pattern.beatsPerMeasure - _countInLeft;
    if (step % _pattern.beatsPerMeasure == 0) {
      _engine.schedule(_clickSound, step == 0 ? 1.0 : _beatVolume, frame);
      final beat = step ~/ _pattern.beatsPerMeasure + 1;
      _cue(frame, () => _countInBeat = beat);
    }
    _countInLeft--;
  }

  /// After every [_speedMeasures] loops, adds [_speedBpmIncrement] until reaching [_speedEndingBpm], then keeps
  /// playing at that tempo.
  void _onSpeedLoopComplete() {
    if (_speedMeasuresPlayed + 1 < _speedMeasures) {
      setState(() => _speedMeasuresPlayed++);
    } else {
      setState(() {
        _speedMeasuresPlayed = 0;
        if (_bpm < _speedEndingBpm) _bpm = math.min(_bpm + _speedBpmIncrement, _speedEndingBpm);
      });
    }
  }

  void _stopMetronome() {
    _engine.stop();
    keepScreenAwake(false);
    _displayTimer?.cancel();
    _cues.clear();
    if (!_isPlaying && _flashingBeat.value == -1) return;
    setState(() {
      _isPlaying = false;
      _currentSubdivision = 0;
      _countInBeat = 0;
      _flashingBeat.value = -1;
    });
  }

  void _toggleMetronome() => _isPlaying ? _stopMetronome() : _startMetronome();

  /// Applies a change that alters the beat structure, restarting playback if it was running.
  void _reconfigure(VoidCallback change) {
    final wasPlaying = _isPlaying;
    _stopMetronome();
    setState(change);
    if (wasPlaying) _startMetronome();
  }

  void _setBpm(num bpm) => setState(() => _bpm = bpm.round().clamp(_minBpm, _maxBpm));

  void _handleTap() {
    final now = DateTime.now().millisecondsSinceEpoch;
    _tapTimestamps.add(now);
    if (_tapTimestamps.length > 4) _tapTimestamps.removeAt(0);

    if (_tapTimestamps.length >= 2) {
      final avgInterval = (_tapTimestamps.last - _tapTimestamps.first) / (_tapTimestamps.length - 1);
      _setBpm(60000 / avgInterval);
    }

    _tapResetTimer?.cancel();
    _tapResetTimer = Timer(const Duration(seconds: 3), _tapTimestamps.clear);
  }

  KeyEventResult _handleKey(FocusNode node, KeyEvent event) {
    if (event is! KeyDownEvent) return KeyEventResult.ignored;
    // Don't steal keys while typing a sound name.
    final focusContext = FocusManager.instance.primaryFocus?.context;
    if (focusContext?.findAncestorWidgetOfExactType<EditableText>() != null) {
      return KeyEventResult.ignored;
    }

    final key = event.logicalKey;
    if (key == LogicalKeyboardKey.space) {
      _toggleMetronome();
    } else if (key == LogicalKeyboardKey.enter) {
      _playSound(_tapSoundNow());
    } else if (key == LogicalKeyboardKey.arrowUp) {
      _setBpm(_bpm + 1);
    } else if (key == LogicalKeyboardKey.arrowDown) {
      _setBpm(_bpm - 1);
    } else {
      return KeyEventResult.ignored;
    }
    return KeyEventResult.handled;
  }

  // ---------------------------------------------------------------------------
  // Patterns and sections

  /// The plain metronome: part 0 plays the downbeat, part 1 the other [_time] - 1 beats.
  _Pattern _metronomePattern() {
    return _Pattern(
      measures: _time,
      beatsPerMeasure: 1,
      beats: [List.generate(_time, (i) => i == 0 ? _stepA : _off), List.generate(_time, (i) => i > 0 ? _stepA : _off)],
      sounds: [_clickSound, _clickSound],
      volumes: [1.0, _beatVolume],
    );
  }

  /// The pattern to play: the chosen Suga pattern, or the plain metronome.
  _Pattern _sectionPattern() =>
      _useSuga ? _sugaPattern(_sugaPatterns[_sugaDirection]!, _sugaSounds) : _metronomePattern();

  /// Switches tabs. Leaving Practice stops playback, so a recording doesn't pick up the metronome.
  void _setTab(int tab) {
    if (tab != 0) _stopMetronome();
    setState(() => _tab = tab);
  }

  void _setUseSuga(bool value) {
    _stopMetronome();
    setState(() {
      _useSuga = value;
      _currentBeat = 0;
      _pattern = _sectionPattern();
    });
  }

  void _setClickSound(String sound) {
    setState(() {
      _clickSound = sound;
      if (!_useSuga) _pattern.sounds.fillRange(0, _pattern.parts, sound);
    });
  }

  /// What a tap plays right now. While a Suga pattern plays, it's the other direction's (Down <-> Up) hit nearest
  /// to this moment, so tapping between the pattern's hits fills in the other pattern with its own sounds.
  /// Otherwise it's the tap sound.
  String _tapSoundNow() {
    if (!_useSuga || !_isPlaying || _countInBeat > 0) return _tapSound;
    final other = _sugaSteps[_sugaDirection == 'Down' ? 'Up' : 'Down']!;
    final total = _pattern.totalBeats;
    // Where playback is now, in steps (fractional), counting from the start of the loop.
    final position = _lastBeat + (_engine.playedFrames - _lastBeatFrame) / _framesPerBeat;
    String? nearest;
    var nearestDistance = double.infinity;
    // Look up to one beat either way.
    for (var g = position.round() - _pattern.beatsPerMeasure; g <= position.round() + _pattern.beatsPerMeasure; g++) {
      final beat = g % _loopLength;
      final step = other[_partAt(beat)][beat % total];
      final distance = (g - position).abs();
      if (step != _off && distance < nearestDistance) {
        nearestDistance = distance;
        nearest = _sugaSounds[step - 1];
      }
    }
    return nearest ?? _tapSound;
  }

