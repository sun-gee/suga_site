  Future<void> _loadGrooveSounds() async {
    try {
      final json = await storage.readSettings();
      if (json == null) return;
      final saved = (jsonDecode(json) as Map<String, dynamic>)['grooveSounds'];
      if (saved is! List || !mounted) return;
      setState(() {
        for (var i = 0; i < _sugaSounds.length && i < saved.length; i++) {
          // A sound that no longer exists (a deleted recording) keeps the default.
          final sound = saved[i];
          if (sound is String && _allSounds.contains(sound)) _sugaSounds[i] = sound;
        }
        _pattern = _sectionPattern();
      });
    } catch (e) {
      debugPrint('Could not load settings: $e');
    }
  }

  Future<void> _loadCustomSounds() async {
    try {
      final loaded = <String>[];
      for (final MapEntry(key: name, value: bytes) in (await storage.loadSounds()).entries) {
        if (await _engine.load(name, bytes)) {
          loaded.add(name);
        } else {
          debugPrint('Skipping custom sound "$name": not a WAV file');
        }
      }
      if (!mounted) return;
      setState(() => _customSounds.addAll(loaded));
    } catch (e) {
      debugPrint('Could not load custom sounds: $e');
    }
  }

  void _showSnack(String message, {bool error = true}) {
    if (!mounted) return;
    ScaffoldMessenger.of(
      context,
    ).showSnackBar(SnackBar(content: Text(message), backgroundColor: error ? _danger : _surfaceHigh));
  }

  Future<void> _recordAudio() async {
    if (_isRecording) {
      final path = await _audioRecorder.stop();
      if (!mounted) return;
      setState(() => _isRecording = false);
      if (path != null) {
        await _loadAudio(await storage.readRecording(path), 'Recording.wav');
      } else {
        // The recorder got no audio, e.g. it lost the microphone or the system blocked it mid-recording.
        _showSnack('Nothing was recorded. ${_micHelp()}');
      }
      return;
    }

    if (!await _audioRecorder.hasPermission()) {
      _showSnack('Microphone permission denied');
      return;
    }
    try {
      // Raw mono WAV: no compression or voice processing, so the hit can be trimmed sample-accurately.
      await _audioRecorder.start(
        const RecordConfig(
          encoder: AudioEncoder.wav,
          numChannels: 1,
          autoGain: false,
          echoCancel: false,
          noiseSuppress: false,
        ),
        path: await storage.recordingPath(),
      );
      if (mounted) setState(() => _isRecording = true);
    } catch (e) {
      debugPrint('Could not start recording: $e');
      // Almost always a missing microphone or one the system won't let the app use.
      _showSnack('Couldn\'t start recording. ${_micHelp()}');
    }
  }

  static String _micHelp() => !kIsWeb && defaultTargetPlatform == TargetPlatform.windows
      ? 'Check a microphone is connected and that Settings > Privacy & security > Microphone lets desktop apps use it.'
      : 'Check a microphone is connected and the app is allowed to use it.';

  Future<void> _uploadAudio() async {
    try {
      final result = await FilePicker.platform.pickFiles(
        type: FileType.custom,
        allowedExtensions: ['wav'],
        withData: true,
      );
      final file = result?.files.single;
      if (file?.bytes != null && mounted) await _loadAudio(file!.bytes!, file.name);
    } catch (e) {
      _showSnack('Error selecting file: $e');
    }
  }

  /// Loads a recording or uploaded file named [name] for saving, trimmed so the sound starts exactly on the hit.
  /// Any silence before the hit would make the custom sound play late against the beat.
  Future<void> _loadAudio(Uint8List bytes, String name) async {
    var loaded = bytes;
    String note;
    var trimmed = false;
    try {
      final result = trimWavToHit(bytes);
      if (result != null) {
        loaded = result.bytes;
        trimmed = true;
        note =
            'Starts on the hit: cut ${result.removedLeadMs.round()} ms before it '
            '(${(result.lengthMs / 1000).toStringAsFixed(2)} s long)';
      } else {
        note = name.toLowerCase().endsWith('.wav')
            ? 'Could not find a hit to trim to; using the file as-is'
            : 'Not trimmed: only WAV files can be trimmed to the hit. Any silence at the start will make it play late';
      }
    } catch (e) {
      note = 'Could not trim ($e); using the file as-is';
    }
    if (!mounted) return;
    setState(() {
      _recordedAudio = loaded;
      _loadedAudioName = name;
      _trimNote = note;
      _trimmed = trimmed;
    });
  }

  Future<void> _playPreview() async {
    final bytes = _recordedAudio;
    if (bytes == null) return;
    const previewName = '#preview'; // '#' can't appear in a saved sound's name, so no clash
    if (await _engine.load(previewName, bytes)) {
      _engine.playNow(previewName);
    } else {
      _showSnack('Can\'t play this file: only WAV files are supported');
    }
  }

  Future<void> _saveCustomSound() async {
    final bytes = _recordedAudio;
    if (bytes == null) {
      _showSnack('No audio file loaded');
      return;
    }

    var name = _soundNameController.text.trim().replaceAll(RegExp(r'[^\w\- ]'), '_');
    if (name.isEmpty) name = 'custom_sound_${DateTime.now().millisecondsSinceEpoch}';
    if (_builtInSounds.contains(name)) {
      _showSnack('"$name" is a built-in sound name');
      return;
    }

    try {
      if (!await _engine.load(name, bytes)) {
        _showSnack('Can\'t use this file: only WAV files are supported');
        return;
      }
      await storage.saveSound(name, bytes);
      if (!mounted) return;
      setState(() {
        _customSounds.add(name);
        _recordedAudio = null;
        _soundNameController.clear();
      });
      _showSnack('Custom sound "$name" saved successfully!', error: false);
    } catch (e) {
      _showSnack('Error saving sound: $e');
    }
  }

  Future<void> _deleteCustomSound(String name) async {
    setState(() {
      _customSounds.remove(name);
      // Anything still pointing at the deleted sound falls back to its default.
      for (var i = 0; i < _sugaSounds.length; i++) {
        if (_sugaSounds[i] == name) _sugaSounds[i] = _defaultSugaSounds[i];
      }
      if (_clickSound == name) _clickSound = _defaultClickSound;
      _pattern = _sectionPattern(); // Rebuilt from the sounds above
      if (_tapSound == name) _tapSound = _defaultTapSound;
    });
    await _engine.unload(name);
    _saveGrooveSounds();
    try {
      await storage.deleteSound(name);
    } catch (e) {
      debugPrint('Could not delete sound "$name": $e');
    }
  }

