                        (v) => setState(() => _speedEndingBpm = v),
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 12),
                Row(
                  children: [
                    Expanded(
                      child: _intPicker(
                        'Every',
                        _speedMeasures,
                        const [1, 2, 3, 4, 6, 8],
                        (v) => '$v ${v == 1 ? loopWord : unit}',
                        (v) => setState(() => _speedMeasures = v),
                      ),
                    ),
                    Expanded(
                      child: _intPicker(
                        'Add',
                        _speedBpmIncrement,
                        const [1, 2, 3, 4, 5, 10],
                        (v) => '+$v BPM',
                        (v) => setState(() => _speedBpmIncrement = v),
                      ),
                    ),
                  ],
                ),
                const SizedBox(height: 10),
                const Text(
                  'Speeds up from Start to Stop, then keeps playing at the Stop tempo.',
                  style: TextStyle(fontSize: 11, color: _textMuted),
                ),
              ],
            ),
          ),
        ],
      ],
    );
  }

  /// Turning Speed Up on starts it from the current tempo, and mid-play it waits a full [_speedMeasures] loops
  /// before the first increase. Turning it off mid-play keeps the tempo it has reached.
  void _setSpeedEnabled(bool value) {
    setState(() {
      _speedEnabled = value;
      if (value) {
        _speedStartBpm = _bpm;
        _speedMeasuresPlayed = 0;
      }
    });
  }

